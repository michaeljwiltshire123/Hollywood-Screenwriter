import { printHtmlInPlace, PrintOptions } from '../../../lib/print/printHtmlInPlace';

export function escapeHsHtml(text: string | undefined): string {
  return (text || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export function printHsHtml(htmlContent: string, options?: PrintOptions): void {
  printHtmlInPlace(htmlContent, options);
}

export function triggerFileDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
